function placeMokebsBeforeFactory(route){


const factoryIndex=Math.floor(route.length*0.72);


// فقط تا قبل کارخانه روغن
const usableRoute=route.slice(
0,
factoryIndex
);



mokebs.forEach((m,i)=>{


if(m.lat && m.lng)
return;



const index=Math.floor(
(i*(usableRoute.length-1)) /
(mokebs.length-1)
);


const point=usableRoute[index];


m.lat=point[0];
m.lng=point[1];


});


}




